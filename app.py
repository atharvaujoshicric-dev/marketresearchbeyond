"""
Spydarr Dashboard (rebuilt)
---------------------------
Upload a raw registration export (.csv or .xlsx). If the file is an .xlsx
workbook, the sheet named "in" is read (case-insensitive match; falls back
to the first sheet if no sheet is named "in"). CSVs are read as-is.

Core logic (all written from scratch):
1. Resolve "Area Type" per row -> 'carpet' / 'usable_carpet' / '' (blank).
   Blank cells are filled with the most frequently occurring non-blank
   Area Type for that Property (mode). Existing non-blank values are
   never touched.
2. The "Area" column is treated as already being in SQ.FT.
3. If (and only if) the resolved Area Type for a row is exactly 'carpet'
   (not usable/useable carpet), the Property Description is scanned for
   balcony / enclosed / open / utility / terrace components (Marathi /
   Hindi / English, in sq.mt or sq.ft) and their sq.ft-equivalent is
   ADDED on top of the Area column value. Parking and other non-livable
   mentions are excluded.
4. Final Carpet Area (SQ.FT) = Area [+ additional components if 'carpet'].
   Carpet Area (SQ.MT) = Carpet Area (SQ.FT) / 10.764.
   Saleable Area = Carpet Area (SQ.FT) * Loading Factor (user input).
   APR = Consideration Value / Saleable Area.
   Configuration = derived from user-supplied 1/2/3 BHK sq.ft thresholds;
   anything at/above the 3 BHK threshold is '4 BHK'.
5. Output workbook: 'Raw Data' (original + 5 new columns appended at the
   very end) and 'Summary' (grouped stats per Location/Property/Config).

Email sending logic and BHK-threshold-driven Configuration logic are
carried over conceptually from the earlier dashboard; everything else
(area extraction, area-type resolution, aggregation, formatting) is
built fresh for this spec.
"""

