# AREA-TYPE RESOLUTION
# =========================================================================
def normalize_area_type(val):
    """Map a raw Area Type cell to 'carpet' / 'usable_carpet' / '' (blank)."""
    if pd.isna(val):
        return ""
    s = re.sub(r"\s+", " ", str(val).strip().lower())
    if s == "":
        return ""
    if "usable" in s or "useable" in s:
        return "usable_carpet"
    if "carpet" in s:
        return "carpet"
    return ""


def resolve_area_types(df, area_type_col, property_col):
    """
    Return a Series aligned to df.index with resolved area types
    ('carpet' / 'usable_carpet' / ''). Blank cells are filled with the
    most frequently occurring non-blank Area Type for that Property.
    """
    normalized = df[area_type_col].apply(normalize_area_type)

    helper = pd.DataFrame({"prop": df[property_col], "norm": normalized})
    non_blank = helper[helper["norm"] != ""]

    if len(non_blank) > 0:
        mode_per_property = (
            non_blank.groupby("prop")["norm"]
            .agg(lambda s: s.value_counts().idxmax())
            .to_dict()
        )
    else:
        mode_per_property = {}

    resolved = normalized.copy()
    blank_mask = resolved == ""
    resolved.loc[blank_mask] = df.loc[blank_mask, property_col].map(mode_per_property).fillna("")
    return resolved


# =========================================================================
# ADDITIONAL AREA (BALCONY / UTILITY / TERRACE / ENCLOSED / OPEN) EXTRACTION
# =========================================================================
M_UNIT = (
    r"(?:चौरस\s*मी(?:[टत]र)?|चौ[\.\s]*मी[\.\s]*|चाै[\.\s]*मी[\.\s]*"
    r"|sq\.?\s*m(?:tr)?\.?|square\s*meter(?:s)?)"
)
F_UNIT = (
    r"(?:चौरस\s*फु[टत]|चौरस\s*फू[टत]|चौ[\.\s]*फु[टत]?|चौ[\.\s]*फू[टत]?"
    r"|sq\.?\s*f(?:t)?\.?|square\s*f(?:ee|oo)t)"
)

# Words that, if found just before a matched number+unit, indicate that
# number is a balcony / utility / terrace / enclosed / open component.
COMPONENT_KEYWORDS = [
    "बाल्कनी", "balcony", "इन्क्लोज्ड", "क्लोज्ड", "बंदिस्त",
    "ओपन", "open", "enclosed", "लगतच", "युटिलिटी", "utility",
    "टेरेस", "terrace", "ड्राय", "dry", "अटॅच",
]

# Words that, if found just before a matched number+unit, mean that number
# should be excluded entirely (parking, land/plot stats, reserved area, etc).
EXCLUDE_KEYWORDS = [
    "पार्किंग", "पार्कींग", "parking", "road", "reserve", "राखीव",
    "प्लॉट", "plot", "वाढीव", "पैकी", "अविभक्त", "साईज", "size",
    "बिल्डअप", "मुल्यांकन", "दर", "rate", "७/१२", "नाकाश",
]

CONTEXT_WINDOW = 45  # characters looked at before a matched number

# Descriptions frequently restate the SAME figure in both units, e.g.
# "13.34 चौ.मी. म्हणजेच 143 चौ.फुट" ("i.e. 143 sq.ft"). Without stripping
# the restatement, both numbers would be picked up and summed, doubling
# that component. This removes the "म्हणजेच <value> <unit>" restatement,
# keeping only the first-stated figure.



_DEDUP_RESTATEMENT = re.compile(
    rf"म्हणजे[च]?\s*\d+\.?\d*\s*(?:{M_UNIT}|{F_UNIT})", re.IGNORECASE
)


def _clean_text(text):
    text = " ".join(str(text).split())
    text = re.sub(r"(\d+)\s*\.\s*(\d+)", r"\1.\2", text)   # fix "12 . 5" -> "12.5"
    text = re.sub(r"(\d),(\d)", r"\1\2", text)             # fix "1,250" -> "1250"
    text = _DEDUP_RESTATEMENT.sub("", text)                # drop unit-restatement duplicates
    return text


def extract_additional_area_sqft(description):
    """
    Scan the (Marathi/Hindi/English) Property Description for balcony /
    enclosed / open / utility / terrace figures given in sq.mt and/or
    sq.ft, and return their SUM converted to sq.ft. Parking-dimension
    patterns (e.g. '2.25 मी. X 4.5 मी.') and excluded-keyword numbers are
    skipped.
    """
    if pd.isna(description) or str(description).strip() == "":
        return 0.0

    text = _clean_text(description)
    # neutralise parking-style "A x B" dimension strings so they can't be
    # mistaken for a standalone area figure
    text = re.sub(r"\d+\.?\d*\s*[xX\*]\s*\d+\.?\d*", "DIM", text)

    total_sqft = 0.0
    for unit_pattern, is_metric in [(M_UNIT, True), (F_UNIT, False)]:
        for match in re.finditer(rf"(\d+\.?\d*)\s?{unit_pattern}", text, re.IGNORECASE):
            value = float(match.group(1))
            context_before = text[max(0, match.start() - CONTEXT_WINDOW):match.start()].lower()

            if any(kw.lower() in context_before for kw in EXCLUDE_KEYWORDS):
                continue
            if any(kw.lower() in context_before for kw in COMPONENT_KEYWORDS):
                total_sqft += value * 10.764 if is_metric else value

    return round(total_sqft, 3)


# =========================================================================
# CONFIGURATION (BHK) DERIVATION
# =========================================================================
def determine_config(carpet_sqft, t1, t2, t3):
    if carpet_sqft <= 0:
        return "N/A"
    if carpet_sqft < t1:
        return "1 BHK"
    elif carpet_sqft < t2:
        return "2 BHK"
    elif carpet_sqft < t3:
        return "3 BHK"
    else:
        return "4 BHK"


