        t2 = st.sidebar.number_input("2 BHK Threshold (< )", value=850)
        t3 = st.sidebar.number_input("3 BHK Threshold (< , else 4 BHK)", value=1100)
        loading_factor = st.sidebar.number_input(
            "Loading Factor", min_value=1.0, value=1.35, step=0.001, format="%.3f"
        )

        with st.spinner("Calculating..."):
            df[area_col] = pd.to_numeric(df[area_col], errors="coerce").fillna(0.0)
            df[cons_col] = pd.to_numeric(df[cons_col], errors="coerce").fillna(0.0)

            resolved_type = resolve_area_types(df, area_type_col, prop_col)

            additional_sqft = df[desc_col].apply(extract_additional_area_sqft)
            # Only ADD the balcony/utility/etc. components when the resolved
            # Area Type is exactly 'carpet' (not usable/useable carpet, not blank)
            additional_sqft = additional_sqft.where(resolved_type == "carpet", 0.0)

